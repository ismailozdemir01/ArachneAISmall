const t = (key) => translations[uiLanguage][key] || key;

function showToast(message) {
  const toast = $("#toast");
  toast.textContent = message;
  toast.classList.add("visible");
  window.clearTimeout(showToast.timer);
  showToast.timer = window.setTimeout(() => toast.classList.remove("visible"), 3200);
}
function applyLanguage() {
  document.documentElement.lang = uiLanguage;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = t(node.dataset.i18n);
    if (value) node.textContent = value;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });
  $("#language-toggle").textContent = uiLanguage === "tr" ? "EN" : "TR";
}
function addMessage(role, text, meta = "") {
  welcome.hidden = true;
  const article = document.createElement("article");
  article.className = `message ${role}`;
  const avatar = document.createElement("div");
  avatar.className = "message-avatar";
  avatar.textContent = role === "user" ? "U" : "A";
  const body = document.createElement("div");
  body.className = "message-body";
  const label = document.createElement("div");
  label.className = "message-role";
  label.textContent = role === "user" ? t("user") : t("assistant");
  const content = document.createElement("div");
  content.className = "message-text";
  content.textContent = text;
  body.append(label, content);
  if (meta) {
    const metadata = document.createElement("div");
    metadata.className = "message-meta";
    metadata.textContent = meta;
    body.append(metadata);
  }
  article.append(avatar, body);
  messages.append(article);
  messages.scrollTop = messages.scrollHeight;
  return { article, content, body };
}
async function refreshStatus() {
  try {
    const response = await fetch("/api/status", { headers: { Accept: "application/json" } });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const data = await response.json();
    runtimePill.className = `status-pill ${data.ready ? "ready" : data.state === "error" ? "error" : "pending"}`;
    runtimePill.querySelector("span").textContent = data.ready ? t("ready") : data.state === "error" ? t("error") : t("missing");
    $("#device-value").textContent = data.device || "—";
    $("#parameter-value").textContent = data.parameter_count ? Number(data.parameter_count).toLocaleString() : "—";
    $("#context-value").textContent = data.context_length ? `${data.context_length.toLocaleString()} tokens` : "—";
    $("#version-value").textContent = data.version ? `v${data.version}` : "v—";
    $("#api-token-wrap").hidden = !data.authentication_required;
    sendButton.disabled = !data.ready || busy;
    if (data.load_error) console.error("Arachne Small load error:", data.load_error);
  } catch (error) {
    runtimePill.className = "status-pill error";
    runtimePill.querySelector("span").textContent = t("error");
    sendButton.disabled = true;
    console.error("Could not read model status:", error);
  }
}
async function submitPrompt(value) {
  const prompt = value.trim();
  if (!prompt) { showToast(t("empty")); return; }
  if (busy) return;
  if (sendButton.disabled) { showToast(t("unavailable")); return; }
  addMessage("user", prompt);
  promptInput.value = "";
  promptInput.style.height = "auto";
  busy = true;
  sendButton.disabled = true;
  const pending = addMessage("assistant", t("thinking"));
  try {
    const response = await fetch("/api/generate", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Accept: "application/json",
        ...($("#api-token").value.trim() ? { Authorization: `Bearer ${$("#api-token").value.trim()}` } : {})
      },
      body: JSON.stringify({
        prompt,
        history: conversationHistory.slice(-20),
        max_new_tokens: Number($("#max-tokens").value),
        temperature: Number($("#temperature").value),
        top_k: 50,
        language: $("#generation-language").value
      })
    });
    const data = await response.json().catch(() => ({}));
    if (!response.ok) throw new Error(data.detail || `HTTP ${response.status}`);
    if (data.text) {
      conversationHistory.push({ role: "user", content: prompt }, { role: "assistant", content: data.text });
      conversationHistory = conversationHistory.slice(-20);
    }
    pending.content.textContent = data.text || (uiLanguage === "tr" ? "Model boş yanıt üretti." : "The model returned an empty response.");
    const metadata = document.createElement("div");
    metadata.className = "message-meta";
    metadata.textContent = `${data.prompt_tokens} prompt · ${data.completion_tokens} completion tokens · ${data.finish_reason}`;
    pending.body.append(metadata);
    if (data.text) {
      const feedbackForm = document.createElement("form");
      feedbackForm.className = "feedback-form";
      const feedbackTitle = document.createElement("strong");
      feedbackTitle.textContent = t("feedbackTitle");
      const correction = document.createElement("textarea");
      correction.required = true;
      correction.maxLength = 8000;
      correction.placeholder = t("correctionPlaceholder");
      const consentLabel = document.createElement("label");
      const consent = document.createElement("input");
      consent.type = "checkbox";
      consent.required = true;
      const consentText = document.createElement("span");
      consentText.textContent = t("consentText");
      consentLabel.append(consent, consentText);
      const rating = document.createElement("select");
      rating.setAttribute("aria-label", "Rating");
      [5, 4, 3, 2, 1].forEach((value) => {
        const option = document.createElement("option");
        option.value = String(value);
        option.textContent = String(value);
        rating.append(option);
      });
      const submit = document.createElement("button");
      submit.type = "submit";
      submit.textContent = t("saveFeedback");
      feedbackForm.append(feedbackTitle, correction, consentLabel, rating, submit);
      feedbackForm.addEventListener("submit", async (event) => {
        event.preventDefault();
        submit.disabled = true;
        try {
          const feedbackResponse = await fetch("/api/feedback", {
            method: "POST",
            headers: {
              "Content-Type": "application/json",
              Accept: "application/json",
              ...($("#api-token").value.trim() ? { Authorization: `Bearer ${$("#api-token").value.trim()}` } : {})
            },
            body: JSON.stringify({
              consent: consent.checked,
              prompt,
              response: data.text,
              correction: correction.value,
              rating: Number(rating.value),
              language: $("#generation-language").value === "auto"
                ? (uiLanguage === "tr" ? "tr" : "en")
                : $("#generation-language").value
            })
          });
          const feedbackData = await feedbackResponse.json().catch(() => ({}));
          if (!feedbackResponse.ok) throw new Error(feedbackData.detail || t("feedbackFailed"));
          submit.textContent = t("feedbackSaved");
          feedbackForm.querySelectorAll("input, textarea, select").forEach((field) => { field.disabled = true; });
        } catch (feedbackError) {
          showToast(feedbackError.message || t("feedbackFailed"));
          submit.disabled = false;
        }
      });
      pending.body.append(feedbackForm);
    }
  } catch (error) {
    pending.content.textContent = `${t("requestFailed")}: ${error.message}`;
    showToast(error.message);
    await refreshStatus();
  } finally {
    busy = false;
    sendButton.disabled = runtimePill.classList.contains("pending") || runtimePill.classList.contains("error");
    messages.scrollTop = messages.scrollHeight;
  }
}
form.addEventListener("submit", (event) => {
  event.preventDefault();
  submitPrompt(promptInput.value);
});
promptInput.addEventListener("input", () => {
  promptInput.style.height = "auto";
  promptInput.style.height = `${Math.min(promptInput.scrollHeight, 180)}px`;
});
promptInput.addEventListener("keydown", (event) => {
  if (event.key === "Enter" && !event.shiftKey) {
    event.preventDefault();
    form.requestSubmit();
  }
});
$("#new-chat").addEventListener("click", () => {
  messages.replaceChildren();
  conversationHistory = [];
  welcome.hidden = false;
  showToast(t("newConversation"));
});
$("#language-toggle").addEventListener("click", () => {
  uiLanguage = uiLanguage === "tr" ? "en" : "tr";
  applyLanguage();
  refreshStatus();
});
document.querySelectorAll(".suggestion").forEach((button) => {
  button.addEventListener("click", () => {
    promptInput.value = button.dataset.prompt || "";
    promptInput.focus();
    promptInput.dispatchEvent(new Event("input"));
  });
});
